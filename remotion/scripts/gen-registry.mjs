// Reads each projects/<slug>/project.json and its compositionConfig.
//   src/registry.gen.tsx     — imports every shot for Root.tsx
//   src/shots.manifest.json  — metadata for the bulk renderer
// Run before `remotion studio` / render. VidTSX-skill files drop in and are picked up automatically.
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync, lstatSync, readlinkSync, symlinkSync, unlinkSync } from 'node:fs';
import { fileURLToPath } from 'url';
import path from 'path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const workspace = path.dirname(root);
const projectsDir = path.join(workspace, 'projects');
const publicDir = path.join(root, '.public');
const publicProjects = path.join(publicDir, 'projects');

function link(target, destination) {
  try {
    if (lstatSync(destination).isSymbolicLink() && readlinkSync(destination) === target) return;
    throw new Error(`Remove conflicting generated path: ${destination}`);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  symlinkSync(target, destination, 'dir');
}

mkdirSync(publicProjects, {recursive:true});
for (const name of ['library','templates']) link(path.join(workspace,name),path.join(publicDir,name));
// Project TSX is outside remotion/. Resolve the same React and Remotion instance in both places.
const dependencies = path.join(workspace,'node_modules');
if (!existsSync(dependencies) && existsSync(path.join(root,'node_modules'))) {
  link('remotion/node_modules',dependencies);
}

function parseConfig(src) {
  const block = /export\s+const\s+compositionConfig\s*=\s*{([\s\S]*?)}\s*;/.exec(src);
  if (!block) return null;
  const body = block[1];
  const str = (k) => { const m = new RegExp(k + "\\s*:\\s*['\"]([^'\"]+)['\"]").exec(body); return m ? m[1] : undefined; };
  const num = (k) => { const m = new RegExp(k + "\\s*:\\s*([0-9.]+)").exec(body); return m ? Number(m[1]) : undefined; };
  const bool = (k) => new RegExp(k + "\\s*:\\s*true").test(body);
  const id = str('id');
  if (!id) return null;
  return {
    id,
    durationInSeconds: num('durationInSeconds') ?? 5,
    fps: num('fps') ?? 30,
    width: num('width') ?? 1920,
    height: num('height') ?? 1080,
    transparent: bool('transparent'),
  };
}

const shots = [];
const seen = new Set();
const projectNames = existsSync(projectsDir)?readdirSync(projectsDir,{withFileTypes:true})
  .filter(entry=>entry.isDirectory()&&/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.name))
  .map(({name})=>name).sort():[];
for (const slug of projectNames) {
  const directory = path.join(projectsDir,slug);
  const descriptor = path.join(directory,'project.json');
  if (!existsSync(descriptor)) continue;
  const project = JSON.parse(readFileSync(descriptor,'utf8'));
  if (project.entry!=='_source/index.tsx') throw new Error(`Invalid entry for ${slug}`);
  const file = path.join(directory,project.entry);
  const cfg = parseConfig(readFileSync(file,'utf8'));
  if (!cfg||cfg.id!==project.composition) throw new Error(`Composition id mismatch for ${slug}`);
  if (seen.has(cfg.id)) throw new Error(`Duplicate composition id: ${cfg.id}`);
  seen.add(cfg.id);
  const imp = path.relative(path.join(root,'src'),file).split(path.sep).join('/').replace(/\.tsx$/,'');
  shots.push({...cfg, project:slug, imp});
  link(path.join(directory,'assets'),path.join(publicProjects,slug));
}
const active = new Set(shots.map(({project})=>project));
for (const name of readdirSync(publicProjects,{withFileTypes:true})) {
  if (name.isSymbolicLink()&&!active.has(name.name)) unlinkSync(path.join(publicProjects,name.name));
}

const header = '// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit.\n';
let reg = header + "import type React from 'react';\n";
shots.forEach((s, i) => { reg += `import Shot${i}, { compositionConfig as cfg${i} } from '${s.imp}';\n`; });
reg += '\nexport const shots: { Comp: React.FC; config: any }[] = [\n';
shots.forEach((s, i) => { reg += `  { Comp: Shot${i} as React.FC, config: cfg${i} },\n`; });
reg += '];\n';
writeFileSync(path.join(root, 'src', 'registry.gen.tsx'), reg);

writeFileSync(
  path.join(root, 'src', 'shots.manifest.json'),
  JSON.stringify(shots.map(({ imp, ...m }) => m), null, 1)
);

console.log(`gen-registry: ${shots.length} shot(s) -> registry.gen.tsx`);
shots.forEach((s) => console.log(`  - ${s.id}  ${s.width}x${s.height}@${s.fps} ${s.durationInSeconds}s${s.transparent ? ' [alpha]' : ''}`));
